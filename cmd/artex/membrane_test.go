package main

import (
	"bytes"
	"strings"
	"testing"

	"github.com/Autumn-27/artex/membrane"
)

func TestMembraneCLIUsage(t *testing.T) {
	var out, errb bytes.Buffer
	if code := runMembrane(nil, &out, &errb); code != 2 || !strings.Contains(errb.String(), "usage") {
		t.Fatalf("no subcommand: code %d, stderr %q", code, errb.String())
	}
	errb.Reset()
	if code := runMembrane([]string{"verify"}, &out, &errb); code != 2 || !strings.Contains(errb.String(), "--task") {
		t.Fatalf("no task: code %d, stderr %q", code, errb.String())
	}
	errb.Reset()
	if code := runMembrane([]string{"verify", "--task", "x1"}, &out, &errb); code != 2 {
		t.Fatalf("bad task: code %d, stderr %q", code, errb.String())
	}
}

// Keys are never generated by verify: missing keys are a clear error.
func TestMembraneCLIMissingKeys(t *testing.T) {
	t.Setenv(membrane.EnvEncKey, "")
	t.Setenv(membrane.EnvHMACKey, "")
	var out, errb bytes.Buffer
	dir := t.TempDir()
	code := runMembrane([]string{"verify", "--task", "1", "--keys-dir", dir}, &out, &errb)
	if code != 1 || !strings.Contains(errb.String(), "membrane keys missing") {
		t.Fatalf("code %d, stderr %q", code, errb.String())
	}
	if membrane.KeysConfigured(dir) {
		t.Fatal("verify generated a key file")
	}
}
